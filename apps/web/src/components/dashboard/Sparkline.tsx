type Props = {
  data: number[];
  color?: string;
  width?: number;
  height?: number;
};

// Inline SVG mini-line z gradientem fill — port wzorca z prototype linii 158-193.
// data.length < 2 → null (jeden punkt nie ma czego rysować). Gradient ID per
// kolor (replace # → safe css selector), kolizja gdy ten sam kolor wiele razy
// na stronie OK (definicja idempotentna).
export function Sparkline({ data, color = '#22d3ee', width = 120, height = 40 }: Props) {
  if (!data || data.length < 2) return null;

  const min = Math.min(...data);
  const max = Math.max(...data);
  const range = max - min || 1;

  const points = data
    .map((v, i) => {
      const x = (i / (data.length - 1)) * width;
      const y = height - ((v - min) / range) * (height - 4) - 2;
      return `${x},${y}`;
    })
    .join(' ');

  const gradId = `sparkline-grad-${color.replace('#', '')}`;

  return (
    <svg
      className="sparkline"
      width={width}
      height={height}
      viewBox={`0 0 ${width} ${height}`}
      role="img"
      aria-hidden="true"
    >
      <defs>
        <linearGradient id={gradId} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor={color} stopOpacity="0.3" />
          <stop offset="100%" stopColor={color} stopOpacity="0" />
        </linearGradient>
      </defs>
      <polygon points={`0,${height} ${points} ${width},${height}`} fill={`url(#${gradId})`} />
      <polyline
        points={points}
        fill="none"
        stroke={color}
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    </svg>
  );
}
